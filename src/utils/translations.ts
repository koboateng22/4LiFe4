/**
 * Returns translated string for a given key and language code.
 * Falls back to Akan/Twi for Fante (fat), or English if key not found.
 */
/**
 * True when `t(key, lang)` returns hand-written text in a language other than English.
 * Those labels are marked translate="no" so Google Translate does not translate them twice.
 */
export function isHandTranslated(key: TranslationKey, langCode?: string): boolean {
  const code = (langCode || 'en').toLowerCase();
  if (code === 'en') return false;
  if (TRANSLATIONS[code]?.[key]) return true;
  return code === 'fat' && !!TRANSLATIONS['ak']?.[key];
}

export function t(key: TranslationKey, langCode?: string): string {
  const code = (langCode || 'en').toLowerCase();
  
  // Direct match
  if (TRANSLATIONS[code] && TRANSLATIONS[code][key]) {
    return TRANSLATIONS[code][key]!;
  }

  // Dialect fallbacks:
  // Fante falls back to Akan/Twi
  if (code === 'fat' && TRANSLATIONS['ak'] && TRANSLATIONS['ak'][key]) {
    return TRANSLATIONS['ak'][key]!;
  }

  // Fallback to English
  return TRANSLATIONS['en']?.[key] || key;
}

